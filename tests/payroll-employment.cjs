const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const storage = new Map();
const month = { value: '2026-11' };
const context = vm.createContext({ console, window: {}, document: { querySelector: () => month },
  localStorage: { getItem: key => storage.get(key) || null, setItem: (key,value) => storage.set(key,value), removeItem: key => storage.delete(key) } });
vm.runInContext(fs.readFileSync('src/payroll-30day.js','utf8').replace(/^import .*;\r?\n/gm,'').replace(/export function /g,'function '), context);
vm.runInContext(`employeeMasterRows = normalizeEmployeeMasterRows([{id:'PH006',name:'Test',hireDate:'2026-09-01',baseSalary:1228,mealAllowance:0}]);`,context);
const load = m => { month.value=m; return context.completePayrollRows(m,[]); };
const nov = load('2026-11');
assert.equal(context.getVisiblePayrollRows(nov).length,4);
assert.equal(context.getVisiblePayrollRows(nov).reduce((s,r)=>s+r.monthlySalaryTotal,0),220000);
assert.equal(nov.find(r=>r.id==='PH006').netPay,0);
assert.equal(context.getEmployeeLastWorkingDate({id:'PH006'}),'2026-10-20');
assert.equal(context.normalizeEmployeeMasterRows([{id:'PH006'}]).find(r=>r.id==='PH006').lastWorkingDate,'2026-10-20');
const oct = load('2026-10');
assert.equal(context.getVisiblePayrollRows(oct).length,5);
assert.equal(oct.find(r=>r.id==='PH005').baseSalary,27000);
month.value='2026-11';
nov.find(r=>r.id==='PH003').dutyAllowance=7500;
const saved = nov.map(context.cleanPayrollRowForStorage);
assert.equal(context.completePayrollRows('2026-11',saved).find(r=>r.id==='PH003').dutyAllowance,7500);
assert.equal(load('2026-12').find(r=>r.id==='PH003').dutyAllowance,0);
const snapshot = [{id:'PH006',employedDays:30,baseSalary:12345,netPay:11234}];
assert.equal(JSON.stringify(context.completePayrollRows('2026-11',snapshot,{status:'paid'})),JSON.stringify(snapshot));
vm.runInContext(`payrollStatus={status:'paid'}; payrollRows=[{id:'PH006',employedDays:30,netPay:11234}];`,context);
assert.equal(context.getVisiblePayrollRows().length,1);
assert.equal(context.getCalculatedRows()[0].netPay,11234);
assert.equal(context.getEmployeeLastWorkingDate({id:'PH006',lastWorkingDate:''}),'');
console.log('Payroll employment and monthly baseline tests passed.');
